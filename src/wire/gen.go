// Docs carries doc comments into the generated TypeScript: by type name, and
// by "Type.Field". wiregen reads them from this package's source; the runtime
// version hash is computed without them.
type Docs struct {
	Types  map[string]string
	Fields map[string]string
}

// HashPrefix starts gen.ts's second line; the hash covers everything after
// that line.
const HashPrefix = "// schema-hash: sha256:"

// Header is gen.ts's first line.
const Header = "// Code generated by plugins/browser/src/cmd/wiregen from plugins/browser/src/wire. DO NOT EDIT."

var (
	versionOnce sync.Once
	version     string
)

// Version is the protocol's identity: the first 16 hex of the sha256 of the
// generated schema without comments. Any change to a route, field, type or
// synthetic action changes it, and since the plugin decodes strictly
// (unknown fields refused), any change IS a breaking one: the ticket refuses a
// mismatch rather than fail field by field. A doc edit is not one, so no
// comment reaches the hash: Docs{} leaves out the type and field docs, and
// withoutComments the route, event and alias docs schema writes itself.
func Version() string {
	versionOnce.Do(func() {
		version = versionOf(schema(Docs{}))
	})
	return version
}

func versionOf(schemaText string) string {
	sum := sha256.Sum256([]byte(withoutComments(schemaText)))
	return hex.EncodeToString(sum[:])[:16]
}

// withoutComments drops every comment line of the generated schema. schema
// writes each comment on lines of its own, and no declaration line starts
// with a comment marker or "*".
func withoutComments(s string) string {
	var b strings.Builder
	for _, l := range strings.SplitAfter(s, "\n") {
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "/*") || strings.HasPrefix(t, "*") || strings.HasPrefix(t, "//") {
			continue
		}
		b.WriteString(l)
	}
	return b.String()
}

// TypeScript is the complete gen.ts: header, hash line, body.
func TypeScript(d Docs) string {
	body := schema(d) + "\n/** This protocol's identity; the ticket request carries it. */\nexport const WIRE_VERSION = '" + Version() + "';\n"
	sum := sha256.Sum256([]byte(body))
	return Header + "\n" + HashPrefix + hex.EncodeToString(sum[:]) + "\n" + body
}

type gen struct {
	d     Docs
	named map[string]reflect.Type
	order []string
}

// schema renders every extension-facing declaration (dev routes excluded).
func schema(d Docs) string {
	g := &gen{d: d, named: map[string]reflect.Type{}}
	for _, r := range Routes {
		if r.Dev {
			continue
		}
		g.collect(reflect.TypeOf(r.Req))
		if r.Resp != nil {
			g.collect(reflect.TypeOf(r.Resp))
		}
	}
	for _, e := range StreamEvents {
		g.collect(reflect.TypeOf(e.Data))
	}
	for _, a := range SyntheticActions {
		g.collect(reflect.TypeOf(a.Params))
	}
	sort.Strings(g.order)

	var b strings.Builder
	b.WriteString("/* eslint-disable */\n")
	b.WriteString("// The extension <-> browser plugin protocol. Source: the Go package\n")
	b.WriteString("// plugins/browser/src/wire (types.go, events.go, routes.go).\n\n")

	for _, a := range TSAliases {
		b.WriteString(g.doc("", a.Doc))
		fmt.Fprintf(&b, "export type %s = %s;\n\n", a.Name, a.Type)
	}
	for _, name := range g.order {
		g.writeType(&b, name, g.named[name])
	}

	// Routes.
	b.WriteString("/** The POST routes: path -> request body and reply. */\nexport interface PostRoutes {\n")
	for _, r := range Routes {
		if r.Dev || r.Method != "POST" {
			continue
		}
		b.WriteString(g.indentDoc("  ", r.Doc))
		fmt.Fprintf(&b, "  '%s': { req: %s; resp: %s };\n", r.Path, g.ref(reflect.TypeOf(r.Req)), g.ref(reflect.TypeOf(r.Resp)))
	}
	b.WriteString("}\n\n/** The PUT routes: path -> request body (the whole state it replaces) and reply. */\nexport interface PutRoutes {\n")
	for _, r := range Routes {
		if r.Dev || r.Method != "PUT" {
			continue
		}
		b.WriteString(g.indentDoc("  ", r.Doc))
		fmt.Fprintf(&b, "  '%s': { req: %s; resp: %s };\n", r.Path, g.ref(reflect.TypeOf(r.Req)), g.ref(reflect.TypeOf(r.Resp)))
	}
	b.WriteString("}\n\n/** The GET routes: path -> query parameters and reply (the event stream is EVENTS_PATH). */\nexport interface GetRoutes {\n")
	for _, r := range Routes {
		if r.Dev || r.Method != "GET" || r.Stream() {
			continue
		}
		b.WriteString(g.indentDoc("  ", r.Doc))
		fmt.Fprintf(&b, "  '%s': { query: %s; resp: %s };\n", r.Path, g.ref(reflect.TypeOf(r.Req)), g.ref(reflect.TypeOf(r.Resp)))
	}
	b.WriteString("}\n\nexport type PostPath = keyof PostRoutes;\nexport type PutPath = keyof PutRoutes;\nexport type GetPath = keyof GetRoutes;\n\n")
	b.WriteString(g.doc("", Events.Doc+" Query: EventsQuery."))
	fmt.Fprintf(&b, "export const EVENTS_PATH = '%s';\n\n", Events.Path)

	// Stream.
	b.WriteString("/** The named SSE events and their data. */\nexport interface StreamEvents {\n")
	for _, e := range StreamEvents {
		fmt.Fprintf(&b, "  %s: %s;\n", e.Name, g.ref(reflect.TypeOf(e.Data)))
	}
	b.WriteString("}\n\n/** The actions this plugin mints itself, with their params. */\nexport type SyntheticActionEvent =\n")
	for _, a := range SyntheticActions {
		fmt.Fprintf(&b, "  | { action: '%s'; params: %s; correlation_id?: string }\n", a.Name, g.ref(reflect.TypeOf(a.Params)))
	}
	b.WriteString(";\n\nexport const SYNTHETIC_ACTIONS = [\n")
	for _, a := range SyntheticActions {
		fmt.Fprintf(&b, "  '%s',\n", a.Name)
	}
	b.WriteString("] as const;\n")
	return b.String()
}

var (
	rawMessageType = reflect.TypeOf(json.RawMessage{})
	timeType       = reflect.TypeOf(time.Time{})
)

type tsTyper interface{ TSType() string }

func overrides(t reflect.Type) (string, bool) {
	if t.Implements(reflect.TypeOf((*tsTyper)(nil)).Elem()) {
		return reflect.Zero(t).Interface().(tsTyper).TSType(), true
	}
	return "", false
}

// collect records every named type reachable from t.
func (g *gen) collect(t reflect.Type) {
	if t == nil {
		return
	}
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice:
		if t == rawMessageType {
			return
		}
		g.collect(t.Elem())
		if t.Kind() == reflect.Slice && t.Name() != "" && t.PkgPath() == thisPkg {
			g.add(t)
		}
		return
	case reflect.Map:
		g.collect(t.Elem())
		return
	case reflect.Struct:
		if t == timeType {
			return
		}
		if t.Name() != "" && g.add(t) {
			for i := 0; i < t.NumField(); i++ {
				f := t.Field(i)
				if f.IsExported() {
					g.collect(f.Type)
				}
			}
		}
	}
}

var thisPkg = reflect.TypeOf(Ack{}).PkgPath()

func (g *gen) add(t reflect.Type) bool {
	if prev, ok := g.named[t.Name()]; ok {
		if prev != t {
			panic(fmt.Sprintf("wire: two types named %s", t.Name()))
		}
		return false
	}
	g.named[t.Name()] = t
	g.order = append(g.order, t.Name())
	return true
}

func (g *gen) writeType(b *strings.Builder, name string, t reflect.Type) {
	b.WriteString(g.doc("", g.d.Types[name]))
	if ts, ok := overrides(t); ok {
		fmt.Fprintf(b, "export type %s = %s;\n\n", name, ts)
		return
	}
	if t.Kind() != reflect.Struct {
		fmt.Fprintf(b, "export type %s = %s;\n\n", name, g.expr(t))
		return
	}
	fields := jsonFields(t)
	if len(fields) == 0 {
		fmt.Fprintf(b, "export type %s = Record<string, never>;\n\n", name)
		return
	}
	fmt.Fprintf(b, "export interface %s {\n", name)
	for _, f := range fields {
		b.WriteString(g.indentDoc("  ", g.d.Fields[name+"."+f.goName]))
		opt := ""
		if f.optional {
			opt = "?"
		}
		ts := f.ts
		if ts == "" {
			ts = g.fieldExpr(f.typ, f.optional)
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", f.name, opt, ts)
	}
	b.WriteString("}\n\n")
}

// ref is a type's name when it has one, else its expression.
func (g *gen) ref(t reflect.Type) string {
	if t.Name() != "" && t.PkgPath() == thisPkg {
		return t.Name()
	}
	return g.expr(t)
}

// fieldExpr: a non-optional slice or map can arrive as null (Go's nil).
func (g *gen) fieldExpr(t reflect.Type, optional bool) string {
	e := g.expr(t)
	if !optional && t != rawMessageType && (t.Kind() == reflect.Slice || t.Kind() == reflect.Map) && t.Name() == "" {
		return e + " | null"
	}
	return e
}

func (g *gen) expr(t reflect.Type) string {
	if ts, ok := overrides(t); ok && t.Name() == "" {
		return ts
	}
	if t.Name() != "" && t.PkgPath() == thisPkg {
		return t.Name()
	}
	switch {
	case t == rawMessageType:
		return "unknown"
	case t == timeType:
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Pointer:
		return g.expr(t.Elem())
	case reflect.Slice, reflect.Array:
		inner := g.expr(t.Elem())
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		return inner + "[]"
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic("wire: map key must be a string: " + t.String())
		}
		return "Record<string, " + g.expr(t.Elem()) + ">"
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		return "{ " + strings.Join(inlineFields(g, t), " ") + " }"
	}
	panic("wire: no TypeScript for " + t.String())
}

func inlineFields(g *gen, t reflect.Type) []string {
	var out []string
	for _, f := range jsonFields(t) {
		opt := ""
		if f.optional {
			opt = "?"
		}
		ts := f.ts
		if ts == "" {
			ts = g.fieldExpr(f.typ, f.optional)
		}
		out = append(out, fmt.Sprintf("%s%s: %s;", f.name, opt, ts))
	}
	return out
}

type jsonField struct {
	name, goName, ts string
	optional         bool
	typ              reflect.Type
	index            int
}

// jsonFields lists a struct's wire fields (json name, optionality).
func jsonFields(t reflect.Type) []jsonField {
	var out []jsonField
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		if f.Anonymous {
			panic("wire: embedded fields are not supported: " + t.Name())
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		out = append(out, jsonField{
			name:     name,
			goName:   f.Name,
			ts:       f.Tag.Get("ts"),
			optional: strings.Contains(","+opts+",", ",omitempty,") || f.Type.Kind() == reflect.Pointer,
			typ:      f.Type,
			index:    i,
		})
	}
	return out
}

// QueryFields maps a GET request type's json names to struct field indexes.
// Every field must be a string: a query parameter is text.
func QueryFields(t reflect.Type) map[string]int {
	out := map[string]int{}
	for _, f := range jsonFields(t) {
		if f.typ.Kind() != reflect.String {
			panic("wire: query fields must be strings: " + t.Name() + "." + f.goName)
		}
		out[f.name] = f.index
	}
	return out
}

func (g *gen) doc(indent, text string) string {
	return g.indentDoc(indent, text)
}

// indentDoc renders a JSDoc block; empty text renders nothing.
func (g *gen) indentDoc(indent, text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		return indent + "/** " + lines[0] + " */\n"
	}
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		if l == "" {
			b.WriteString(indent + " *\n")
		} else {
			b.WriteString(indent + " * " + l + "\n")
		}
	}
	b.WriteString(indent + " */\n")
	return b.String()
}
