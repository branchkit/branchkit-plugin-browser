package wire

import (
	"fmt"
	"reflect"
	"strings"
)

// MarkdownHeader is WIRE.md's first line.
const MarkdownHeader = "<!-- Code generated by src/cmd/wiregen -md from src/wire. DO NOT EDIT. -->"

// Markdown is WIRE.md: the protocol reference for someone writing an
// extension, from the same declarations as gen.ts. The README says how an
// extension pairs; this says what it may send and receive once it has.
func Markdown(d Docs) string {
	g := &gen{d: d, named: map[string]reflect.Type{}}
	var b strings.Builder
	b.WriteString(MarkdownHeader + "\n\n")
	b.WriteString("# Browser plugin wire protocol\n\n")
	b.WriteString("What an extension and the browser plugin say to each other once paired: every\n")
	b.WriteString("route on the plugin's listener, the events on its stream, and the shape of\n")
	b.WriteString("each body. How an extension pairs in the first place is in the README.\n\n")
	fmt.Fprintf(&b, "`WIRE_VERSION`: `%s`. The ticket request carries it, and a mismatch is\n", Version())
	b.WriteString("refused (409): the plugin decodes strictly, so any change to a route, field\n")
	b.WriteString("or type is a breaking one, and changes the version. A doc edit does not.\n\n")

	b.WriteString("## Authentication\n\n")
	b.WriteString("Every route takes the pairing token as `Authorization: Bearer <token>`,\n")
	b.WriteString("except the event stream, which takes a one-time ticket in its query\n")
	b.WriteString("(`EventSource` cannot send headers): buy one with `POST " + EventsTicket.Path + "`,\n")
	b.WriteString("then open `GET " + Events.Path + "?ticket=…&conn_id=…`. Bodies are JSON; unknown\n")
	b.WriteString("fields are refused.\n\n")

	b.WriteString("## Routes\n\n")
	b.WriteString("| Method | Path | Request | Reply | What it is |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, r := range Routes {
		if r.Dev {
			continue
		}
		req := "`" + g.ref(reflect.TypeOf(r.Req)) + "`"
		if r.Method == "GET" {
			req += " (query)"
		}
		resp := "event stream"
		if !r.Stream() {
			resp = "`" + g.ref(reflect.TypeOf(r.Resp)) + "`"
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s |\n", r.Method, r.Path, req, resp, cell(r.Doc))
	}

	b.WriteString("\n## Stream events\n\n")
	b.WriteString(Events.Doc + " Each named SSE event's data is JSON:\n\n")
	b.WriteString("| Event | Data |\n|---|---|\n")
	for _, e := range StreamEvents {
		fmt.Fprintf(&b, "| `%s` | `%s` |\n", e.Name, g.ref(reflect.TypeOf(e.Data)))
	}

	b.WriteString("\n## Actions the plugin mints\n\n")
	b.WriteString("An `action` event is either a command the extension contributed (its own\n")
	b.WriteString("action name, with the params the platform matched) or one of these:\n\n")
	b.WriteString("| Action | Params |\n|---|---|\n")
	for _, a := range SyntheticActions {
		fmt.Fprintf(&b, "| `%s` | `%s` |\n", a.Name, g.ref(reflect.TypeOf(a.Params)))
	}

	b.WriteString("\n## Types\n\n")
	b.WriteString("As TypeScript, with each type's and field's documentation (the same file the\n")
	b.WriteString("BranchKit extension builds against):\n\n")
	b.WriteString("```ts\n")
	b.WriteString(schema(d))
	fmt.Fprintf(&b, "\nexport const WIRE_VERSION = '%s';\n", Version())
	b.WriteString("```\n")
	return b.String()
}

// cell makes a doc line safe inside a table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}
